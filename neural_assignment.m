function assignment = neural_assignment(costMatrix)
% NEURAL_ASSIGNMENT Решает задачу назначения с помощью нейросети Хопфилда
% и уточняет решение венгерским алгоритмом для обеспечения допустимости.
%   assignment = neural_assignment(costMatrix) возвращает вектор длиной N,
%   где N = size(costMatrix,1), содержащий индексы столбцов (назначения)
%   для каждой строки. Матрица costMatrix может быть прямоугольной;
%   при необходимости она дополняется фиктивными строками/столбцами.
%
%   Алгоритм:
%   1. Дополняет матрицу до квадратной.
%   2. Запускает непрерывную нейросеть Хопфилда для получения вероятностей.
%   3. Применяет венгерский алгоритм к матрице (1 - V) для нахождения
%      допустимого назначения (минимизация стоимости, максимизация V).

    % --- Дополнение до квадратной матрицы ---
    [nRows, nCols] = size(costMatrix);
    if nRows > nCols
        costMatrix = [costMatrix, 1e6 * ones(nRows, nRows - nCols)];
    elseif nCols > nRows
        costMatrix = [costMatrix; 1e6 * ones(nCols - nRows, nCols)];
    end
    N = size(costMatrix, 1);   % теперь квадратная N x N

    % --- Параметры сети ---
    A = 1.0;          % штраф за нарушение ограничения "строка → 1"
    B = 1.0;          % штраф за нарушение ограничения "столбец → 1"
    C = 0.5;          % весовой коэффициент для целевой функции (стоимость)
    dt = 0.01;        % шаг обновления
    maxIter = 2000;
    tol = 1e-6;

    % --- Инициализация состояний нейронов (случайные малые значения) ---
    V = 0.5 + 0.1 * rand(N, N);   % выходы нейронов (вероятности)

    % --- Вспомогательная функция для сигмоиды (логистической) ---
    sigmoid = @(x) 1 ./ (1 + exp(-x));

    % --- Итерационный процесс ---
    for iter = 1:maxIter
        % dE/dV = A * (sum_k V(i,k) - 1) + B * (sum_k V(k,j) - 1) + C * costMatrix
        rowSums = sum(V, 2);       % сумма по строкам
        colSums = sum(V, 1);       % сумма по столбцам

        dE = A * (rowSums - 1) + B * (colSums - 1) + C * costMatrix;
        % dE - матрица NxN

        % Обновление состояний (градиентный спуск с сигмоидой)
        V = sigmoid(V - dt * dE);

        % Проверка сходимости
        if iter > 1 && norm(V - V_prev, 'fro') < tol
            break;
        end
        V_prev = V;
    end

    % --- Уточнение решения венгерским алгоритмом ---
    % Формируем матрицу стоимостей для венгерского алгоритма: 1 - V
    % (чем больше V, тем меньше стоимость, т.е. предпочтительнее)
    costForHungarian = 1 - V;

    % Венгерский алгоритм (ожидается, что функция hungarian_assignment
    % доступна в папке Algorithm)
    assignment_hung = hungarian_assignment(costForHungarian);

    % Если исходная матрица была прямоугольной и мы добавляли фиктивные строки,
    % то возвращаем только назначения для исходных строк.
    if nRows < N
        assignment = assignment_hung(1:nRows);
    else
        assignment = assignment_hung;
    end

    % Если добавляли фиктивные столбцы, некоторые назначения могут указывать
    % на них. В вызывающем коде такие назначения будут проигнорированы.
end